"""Supporting-layer records, data services: cache, queue, search, storage, cdn (plan 4.3, 6.1).

Conventions (same as the core-layer modules):
  * ``regions``/``attest`` of every record registered in ``kb.bindings.BINDINGS`` are overwritten at import from
    ``kb.regions`` / ``kb.compliance`` (single source of truth); ``S(..., bind=(region_key, attest_key))`` registers
    the binding.  A vendor whose region or attestation was not confirmed on an official page has a row full of
    ``UNKNOWN``/``unknown`` there, so the record carries empty regions and ``no`` attestations: it fails closed.
  * Self-managed products bind to ``self_hosted`` (``["*"]`` regions, ``self`` attestations: the team carries the control).
  * Cost bands are USD per month for this component alone at each size class (plan 7); scores are the author's
    judgement per the plan 4.1 rubric.  ``kind`` ``none``/``bundled``/``db_backed`` mark options that add no vendor.
  * ``triggers`` are the requirement tags ``supporting.py`` uses (plan 6.1).

Helpers defined here (``S``, ``A``, ``SELF``) are reused by ``services_app`` and ``services_ops``.
"""
from __future__ import annotations

from . import bindings as _bindings
from .model import fact, service

_ATTR = ("cost_efficiency", "dev_velocity", "scalability", "performance", "maintainability",
         "security", "ecosystem", "learning_curve", "popularity")
SELF = ("self_hosted", "self_hosted")
NO_REG = {"india": [], "eu": [], "us": []}
OSS = dict(self_host=True, saas=False, oss=True, net=False)   # self-managed open-source product


def A(*v):
    return dict(zip(_ATTR, v))


def S(id, name, layer, kind, *, a, ops, sz, cost, caps=(), trig=(), bind=None, rest=False, sel=False, cloud=("any",),
      under=None, self_host=False, saas=True, oss=False, licence="proprietary", net=True, lock=1, best=(), avoid=(),
      free=None, langs=(), plats=(), runtime=None, strengths, tradeoffs, facts=(), sources, status="maintained",
      replaced_by=None, major=None, until=None):
    """One supporting-layer candidate; ``bind`` is ``(kb.regions key, kb.compliance key)`` (either may be None)."""
    if bind:
        _bindings.BINDINGS[id] = bind
    return service(
        id, name, layer, kind, triggers=list(trig), languages=list(langs), platforms=list(plats), attrs=A(*a),
        ops_burden=ops, scale_floor=sz[0], scale_ceiling=sz[1], cost=cost, free_tier=free, self_hostable=self_host,
        saas=saas, open_source=oss, licence=licence, needs_internet=net, cloud_affinity=list(cloud),
        underlying_cloud=under, regions=NO_REG, region_selectable=sel, data_at_rest=rest, attest=None, lock_in=lock,
        caps=list(caps), best_for=list(best), avoid_for=list(avoid), runtime=runtime, status=status,
        replaced_by=replaced_by, current_major=major, supported_until=until, strengths=strengths,
        tradeoffs=tradeoffs, facts=list(facts), sources=sources)


def unverified(text, key, conf="K"):
    """Region/attestation statement for a vendor whose facts live in kb.regions/kb.compliance as unknown."""
    return fact(text, key, conf)


