ALL = ["*"]  # self-hosted: wherever the team deploys it


def _reg(key):
    res = (_ENTRIES.get(key) or {}).get("residency", {})
    out = {}
    for g in ("india", "eu", "us"):
        v = res.get(g, _UNKNOWN)
        out[g] = [] if v == _UNKNOWN else list(v)
    return out


